using System.Numerics;

namespace CallOfSlop;

/// <summary>
/// Player limits per map. A map file may set "maxPlayers" (2-32); otherwise the limit comes from the playable area:
///   Small (under ~75 m across):  8 below 2,500 m², else 10
///   Medium (up to ~135 m):       12 below 9,000 m², else 16
///   Large (beyond):              24 below 30,000 m², else 32
/// Every map needs a spawn point per player. Maps with fewer hand-placed spawns than their limit get extra spawns
/// generated when the map loads (in code, deterministically, so host and clients agree; the map file is never
/// changed): free spots on rings around the hand-placed spawns, on the same floor, in sight of the spawn they grow
/// from, clear of walls, other spawns and moving platforms. If a map can't fit enough, its limit drops to its spawns.
/// The fingerprint (<see cref="ContentHash"/>) covers only the hand-placed spawns, so old maps keep their old one.
/// </summary>
public sealed partial class Map
{
    /// <summary>The most players (people + bots) any server can hold. Player ids are 0..HardMaxPlayers-1.</summary>
    public const int HardMaxPlayers = 32;

    /// <summary>"maxPlayers" from the map file (0: not set, use the size-based default).</summary>
    public int MaxPlayersSetting;

    /// <summary>How many of <see cref="Spawns"/> came from the map itself (the rest were generated by <see cref="EnsureSpawns"/>).</summary>
    public int AuthoredSpawns = -1;

    /// <summary>Spawns added at load time so the map has one per player.</summary>
    public int GeneratedSpawns => AuthoredSpawns < 0 ? 0 : Spawns.Count - AuthoredSpawns;

    /// <summary>The default limit for a map of this size (see the class comment).</summary>
    public int DefaultMaxPlayers
    {
        get
        {
            var area = HalfX * 2 * HalfZ * 2;
            return Size switch
            {
                MapSize.Small => area < 2500 ? 8 : 10,
                MapSize.Medium => area < 9000 ? 12 : 16,
                _ => area < 30000 ? 24 : 32,
            };
        }
    }

    /// <summary>The wanted limit: the file's "maxPlayers", or the size-based default.</summary>
    public int WantedMaxPlayers => Math.Clamp(MaxPlayersSetting > 0 ? MaxPlayersSetting : DefaultMaxPlayers, 2, HardMaxPlayers);

    /// <summary>
    /// The most players (people and bots) this map takes: the wanted limit, lowered to the number of spawns when the
    /// map couldn't fit enough (never below 2). The lobby's bot slider, joins and the map vote all respect it.
    /// </summary>
    public int MaxPlayers => Math.Clamp(Math.Min(WantedMaxPlayers, Math.Max(Spawns.Count, 2)), 2, HardMaxPlayers);

    /// <summary>
    /// Adds generated spawns until there's one per player (<see cref="WantedMaxPlayers"/>). Runs once, at the end of
    /// <see cref="Validate"/>; calling it again changes nothing. Deterministic (no randomness).
    /// </summary>
    public void EnsureSpawns()
    {
        if (AuthoredSpawns >= 0)
            return;
        AuthoredSpawns = Spawns.Count;
        var need = WantedMaxPlayers;
        if (Spawns.Count >= need || Spawns.Count == 0)
            return;
        var authored = Spawns.ToList();
        float[] radii = [3f, 4.5f, 6f, 7.5f, 9f, 11f];
        const int angles = 8;
        for (var ring = 0; ring < radii.Length; ring++)
        for (var k = 0; k < angles; k++)
        foreach (var s in authored) // one candidate around every spawn before a second around any: spread them out
        {
            if (Spawns.Count >= need)
                goto done;
            var a = k * MathF.Tau / angles + ring * 0.39f;
            var c = s + new Vector3(MathF.Cos(a), 0, MathF.Sin(a)) * radii[ring];
            if (SpawnSpotOk(s, ref c))
                Spawns.Add(c);
        }
        done:
        _objectives = null; // team spawns, hills and flags are worked out from the full list
        if (GeneratedSpawns > 0)
            Console.WriteLine($"Map '{Name}': {AuthoredSpawns} spawns for {need} players, generated {GeneratedSpawns} more"
                + (Spawns.Count < need ? $" (only room for {Spawns.Count}: the limit is {MaxPlayers})" : ""));
    }

    /// <summary>Can a generated spawn go at <paramref name="c"/> (grown from the spawn at <paramref name="from"/>)? Fixes up its height.</summary>
    private bool SpawnSpotOk(Vector3 from, ref Vector3 c)
    {
        var fromGround = GroundHeight(from.X, from.Z);
        var onGround = from.Y - fromGround < 0.3f;
        if (onGround)
        {
            c.Y = GroundHeight(c.X, c.Z);
            if (MathF.Abs(c.Y - from.Y) > 1.2f)
                return false;
        }
        else if (!HasFloorAt(c))
            return false; // on a roof or platform: stay on it
        if (BadSpot(c) || InMoverSweep(c))
            return false;
        // Room to stand: most of a ring around it is free too (not jammed against a wall or in a doorway).
        var open = 0;
        for (var k = 0; k < 8; k++)
        {
            var a = k * MathF.Tau / 8;
            if (!IsBlocked(c + new Vector3(MathF.Cos(a), 0, MathF.Sin(a)) * 0.9f))
                open++;
        }
        if (open < 6)
            return false;
        foreach (var s in Spawns)
            if (MathF.Abs(s.Y - c.Y) < 2.5f && new Vector2(s.X - c.X, s.Z - c.Z).Length() < 2.2f)
                return false;
        return InSight(from + new Vector3(0, 1.5f, 0), c + new Vector3(0, 1.5f, 0)); // same room / same side of the wall
    }

    /// <summary>Is there a box top right under <paramref name="feet"/> (flat maps: or the ground at 0)?</summary>
    private bool HasFloorAt(Vector3 feet)
    {
        if (!HasTerrain && MathF.Abs(feet.Y) < 0.05f)
            return true;
        if (HasTerrain && MathF.Abs(feet.Y - GroundHeight(feet.X, feet.Z)) < 0.05f)
            return true;
        foreach (var b in Solid)
            if (feet.X >= b.Min.X && feet.X <= b.Max.X && feet.Z >= b.Min.Z && feet.Z <= b.Max.Z && MathF.Abs(b.Max.Y - feet.Y) < 0.06f)
                return true;
        return false;
    }

    /// <summary>A clear straight line between two points (boxes and terrain), without needing the map to be loaded into the world.</summary>
    private bool InSight(Vector3 a, Vector3 b)
    {
        var d = b - a;
        var len = d.Length();
        if (len < 0.01f)
            return true;
        var dir = d / len;
        foreach (var box in Solid)
            if (box.Raycast(a, dir, len) is { } t && t < len - 0.05f)
                return false;
        if (HasTerrain)
            for (var i = 1; i < 8; i++)
            {
                var p = a + d * (i / 8f);
                if (GroundHeight(p.X, p.Z) > p.Y)
                    return false;
            }
        return true;
    }
}
