using System.Text;
using static CallOfSlop.PartKit.PartKitMath;

namespace CallOfSlop.PartKit.ShipGen;

// The procedural ship generator's shared contract (docs/sandbox/shipgen/README.md): the brief a hull is made to, the dice that
// make its choices, the report that records every choice, and the builder that draws a hull's welded pieces and welds them.
// A faction's generator (TraderHauler, ...) has its own architecture and look and uses these; everything here is per run, so two
// hulls made one after the other share nothing.

/// <summary>What a hull is made for: the faction, the job, the seed, and the shipped name it goes out under (if any). Cockpit, when
/// set, overrides the job's own choice of cockpit room.</summary>
public sealed record ShipBrief(string Faction, string Job, int Seed, string? Name = null, CockpitKind? Cockpit = null);

/// <summary>
/// The cockpit is a room, one of two kinds (Karl, 2026-11-22). <b>Open</b>: a glass canopy, the hull itself as the room's wall above
/// the sill, laid out inside (consoles along the sides under the glass, lined walls, an overhead) so nothing bare shows through
/// the glass. <b>Sealed</b>: a room inside the hull with no glass at all, flying on screens (a combat ship's: nothing to shoot
/// through); the nose outside is plated.
/// </summary>
public enum CockpitKind { Open, Sealed }

/// <summary>Every choice a run made, in the order made, with its stage and why: what the report page and the gallery show.</summary>
public sealed class ChoiceReport
{
    public readonly record struct Entry(string Stage, string What, string Value, string Why);

    public readonly List<Entry> Entries = [];
    public readonly List<(string Stage, string Line)> Notes = [];
    public readonly List<string> Problems = [];

    public void Add(string stage, string what, string value, string why) => Entries.Add(new(stage, what, value, why));

    public void Note(string stage, string line) => Notes.Add((stage, line));

    /// <summary>A rule the hull broke: the run fails with every one listed (nothing is shown with errors).</summary>
    public void Problem(string line) => Problems.Add(line);

    public string Markdown(ShipBrief brief, string title, IEnumerable<string> stages)
    {
        var sb = new StringBuilder();
        sb.Append($"# {title}\n\n");
        sb.Append($"Generated by `--gen-parts shipgen_parts` (Source/ShipGen). Faction: {brief.Faction}. Job: {brief.Job}. Seed: {brief.Seed}.\n");
        sb.Append("Every line below is a choice the generator made, the stage that made it and why. Change the generator, never this file.\n");
        foreach (var stage in stages)
        {
            var es = Entries.Where(e => e.Stage == stage).ToList();
            var ns = Notes.Where(n => n.Stage == stage).ToList();
            if (es.Count == 0 && ns.Count == 0)
                continue;
            sb.Append($"\n## {stage}\n\n");
            if (es.Count > 0)
            {
                sb.Append("| Choice | Value | Why |\n| --- | --- | --- |\n");
                foreach (var e in es)
                    sb.Append($"| {e.What} | {e.Value} | {e.Why} |\n");
            }
            if (ns.Count > 0)
            {
                if (es.Count > 0)
                    sb.Append('\n');
                foreach (var n in ns)
                    sb.Append($"- {n.Line}\n");
            }
        }
        return sb.ToString();
    }
}

/// <summary>
/// The dice: one stream per subject (layout, hull, drive, dress, ...), each seeded from the hull's seed and the stream's name, so a
/// change to how the dress is rolled never moves the layout. Every roll goes into the report with its range and why.
/// </summary>
public sealed class Dice(int seed, ChoiceReport report)
{
    public readonly int Seed = seed;
    private readonly ChoiceReport _report = report;

    public Roll Stream(string name, string stage) => new(Hash(Seed, name), _report, stage);

    private static ulong Hash(int seed, string s)
    {
        var h = 1469598103934665603UL ^ (uint)seed;
        foreach (var c in s)
        {
            h ^= c;
            h *= 1099511628211UL;
        }
        h ^= h >> 31;
        return h == 0 ? 1 : h;
    }
}

/// <summary>One stream of rolls (xorshift64*), each recorded.</summary>
public sealed class Roll(ulong state, ChoiceReport report, string stage)
{
    private ulong _s = state;

    private double Next()
    {
        _s ^= _s >> 12;
        _s ^= _s << 25;
        _s ^= _s >> 27;
        return ((_s * 2685821657736338717UL) >> 11) * (1.0 / (1UL << 53));
    }

    /// <summary>A value from a to b in steps of step (so lengths stay whole centimetres).</summary>
    public double Range(string what, double a, double b, double step, string why)
    {
        var n = (int)Math.Round((b - a) / step);
        var v = Math.Round(a + Math.Min(n, (int)Math.Floor(Next() * (n + 1))) * step, 4);
        report.Add(stage, what, $"{Fmt(v)} (from {Fmt(a)} to {Fmt(b)})", why);
        return v;
    }

    public int Int(string what, int a, int b, string why)
    {
        var v = a + Math.Min(b - a, (int)Math.Floor(Next() * (b - a + 1)));
        report.Add(stage, what, $"{v} (from {a} to {b})", why);
        return v;
    }

    public T Pick<T>(string what, T[] options, Func<T, string> label, string why)
    {
        var v = options[Math.Min(options.Length - 1, (int)Math.Floor(Next() * options.Length))];
        report.Add(stage, what, $"{label(v)} (of {string.Join(", ", options.Select(label))})", why);
        return v;
    }
}

/// <summary>
/// A hull's welded pieces, drawn straight into the piece each box belongs to (In), in ship metres (x across, 0 the centre line;
/// y up; z aft, the bow at -z), moved by half a cell so the body's origin is a cell's middle. Every piece has its origin at the
/// body's. Sockets go on the piece they are drawn in, and their names are unique over the whole hull, so a fitting finds its
/// piece by the socket's name alone. Connect gives each pair of pieces whose solid boxes touch a facing socket pair (the game
/// welds the rest), PlaceOrder places them out from the first.
/// </summary>
public sealed class HullPieces(string prefix, string section, string group = "Ship")
{
    public const double H = 0.125;
    public const double T = 0.04; // a drawn plate's thickness
    private const double Touch = 0.001; // (one tolerance for faces that meet, everywhere)

    public readonly string Prefix = prefix;
    public readonly List<Part> All = [];
    private readonly Dictionary<string, Part> _byName = [];
    public readonly Dictionary<string, string> SockPiece = [];
    private Part? _cur;

    public Part Cur => _cur ?? throw new InvalidOperationException("ShipGen: drawing with no piece");

    public Part Piece(string what, string desc, string color, string role = "frame")
    {
        var name = $"{Prefix} {what}";
        if (_byName.TryGetValue(name, out var p))
            return p;
        if (name.Length > 32)
            throw new InvalidOperationException($"ShipGen: part name {name} is longer than 32 characters");
        p = new Part(name, Small, section, desc, role: role, tool: "welder", material: "steel", color: color, group: group);
        _byName[name] = p;
        All.Add(p);
        return p;
    }

    public Part Named(string what) => _byName[$"{Prefix} {what}"];

    public bool Has(string what) => _byName.ContainsKey($"{Prefix} {what}");

    public void In(Part p, Action a)
    {
        var was = _cur;
        _cur = p;
        a();
        _cur = was;
    }

    /// <summary>How far aft the body's origin is of the ship's z 0 (a whole number of cells, about the hull's middle: what stands on it is kept within 30 m of it).</summary>
    public double ZShift;

    public double[] P(double x, double y, double z) => [x - H, y - H, z - H - ZShift];

    // ---- vector maths

    public static double[] Sub(double[] a, double[] b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
    public static double[] Add(double[] a, double[] b, double s = 1) => [a[0] + b[0] * s, a[1] + b[1] * s, a[2] + b[2] * s];
    public static double[] Cross(double[] a, double[] b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
    public static double Dot(double[] a, double[] b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
    public static double[] Lerp(double[] a, double[] b, double t) => [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];

    public static double[] Unit(double[] a)
    {
        var l = Math.Sqrt(Dot(a, a));
        return [a[0] / l, a[1] / l, a[2] / l];
    }

    // ---- drawing (into the current piece)

    /// <summary>A flat plate through the points (a convex polygon, ship metres), thick about them: a "hull" shape, drawn only.</summary>
    public void Plate(double[][] pts, string color, string finish, bool glass = false, bool glow = false, bool paint = true, double thick = T)
    {
        double[]? n = null;
        for (var i = 2; i < pts.Length && n == null; i++)
        {
            var c = Cross(Sub(pts[1], pts[0]), Sub(pts[i], pts[0]));
            if (Dot(c, c) > 1e-8)
                n = Unit(c);
        }
        if (n == null)
            return;
        var both = new List<double[]>();
        foreach (var q in pts)
            foreach (var s in new[] { -1, 1 })
                both.Add([.. Enumerable.Range(0, 3).Select(k => Py.Round(q[k] - H - (k == 2 ? ZShift : 0) + s * n[k] * thick / 2, 4))]);
        Shaped(both, color, finish, glass, glow, paint);
    }

    /// <summary>A convex solid between two outlines (ship metres): drawn only.</summary>
    public void Prism(double[][] a, double[][] b, string color, string finish, bool glow = false, bool paint = true) =>
        Shaped([.. a.Concat(b).Select(q => P(q[0], q[1], q[2]).Select(x => Py.Round(x, 4)).ToArray())], color, finish, false, glow, paint);

    private void Shaped(List<double[]> pts, string color, string finish, bool glass, bool glow, bool paint)
    {
        double[] mn = [.. Enumerable.Range(0, 3).Select(k => pts.Min(q => q[k]))];
        double[] mx = [.. Enumerable.Range(0, 3).Select(k => pts.Max(q => q[k]))];
        var shape = Kw(("shape", "hull"), ("points", pts.Select(q => (object?)q.Select(x => (object?)x).ToList()).ToList()));
        if (!paint)
            shape["paintable"] = false;
        if (glow)
            shape["glow"] = true;
        else if (!glass)
            shape["finish"] = finish;
        Cur.Add(Box(mn, mx, color, detail: true, glass: glass, shape: shape));
    }

    /// <summary>A quad as one plate when flat, else as two triangles.</summary>
    public void Quad(double[] a, double[] b, double[] c, double[] d, string color, string finish, bool glass = false, bool paint = true)
    {
        var n = Cross(Sub(b, a), Sub(c, a));
        if (Dot(n, n) < 1e-10 || Math.Abs(Dot(Unit(n), Sub(d, a))) < 0.002)
            Plate([a, b, c, d], color, finish, glass, paint: paint);
        else
        {
            Plate([a, b, c], color, finish, glass, paint: paint);
            Plate([a, c, d], color, finish, glass, paint: paint);
        }
    }

    public void Solid(double x0, double y0, double z0, double x1, double y1, double z1, string color, string? finish = null) =>
        Cur.Add(Box(P(Math.Min(x0, x1), Math.Min(y0, y1), Math.Min(z0, z1)), P(Math.Max(x0, x1), Math.Max(y0, y1), Math.Max(z0, z1)), color, shape: finish == null ? null : Kw(("finish", finish))));

    public void Detail(double x0, double y0, double z0, double x1, double y1, double z1, string color, string? finish = null, bool glow = false)
    {
        var shape = finish == null && !glow ? null : new PyDict();
        if (glow)
            shape!["glow"] = true;
        else if (finish != null)
            shape!["finish"] = finish;
        Cur.Add(Box(P(Math.Min(x0, x1), Math.Min(y0, y1), Math.Min(z0, z1)), P(Math.Max(x0, x1), Math.Max(y0, y1), Math.Max(z0, z1)), color, detail: true, shape: shape));
    }

    public void Hidden(double x0, double y0, double z0, double x1, double y1, double z1)
    {
        if (Math.Abs(x1 - x0) < 0.011 || Math.Abs(y1 - y0) < 0.011 || Math.Abs(z1 - z0) < 0.011)
            return;
        Cur.Add(Box(P(Math.Min(x0, x1), Math.Min(y0, y1), Math.Min(z0, z1)), P(Math.Max(x0, x1), Math.Max(y0, y1), Math.Max(z0, z1)), hidden: true));
    }

    /// <summary>A socket on a face of the current piece (ship metres); its name is the hull's, unique over every piece.</summary>
    public void Sock(string name, double x, double y, double z, string dir)
    {
        if (!SockPiece.TryAdd(name, (string)Cur.D["name"]!))
            throw new InvalidOperationException($"ShipGen: socket {name} twice");
        Cur.Sock(name, P(Math.Round(x, 3), Math.Round(y, 3), Math.Round(z, 3)), dir);
    }

    // ---- welding the pieces

    private static double[] Vd(PyDict b, string key) => [.. ((List<object?>)b[key]!).Select(Convert.ToDouble)];

    private static bool Drawn(PyDict b) => b.Get("detail") is true;

    /// <summary>A facing socket pair wherever two pieces' solid boxes touch face to face (on their biggest contact), unless they already
    /// meet at one. Returns the pairs of pieces that touch nowhere (for the report).</summary>
    public void Connect()
    {
        var solid = All.Select(q => q.Boxes.Where(b => !Drawn(b)).Select(b => (Mn: Vd(b, "min"), Mx: Vd(b, "max"))).ToList()).ToList();
        var count = new int[All.Count];
        for (var i = 0; i < All.Count; i++)
            for (var j = i + 1; j < All.Count; j++)
            {
                if (Meet(All[i], All[j]))
                    continue;
                (double Area, double[] At, int Axis, bool IPlus) best = (0, [], 0, false);
                foreach (var A in solid[i])
                    foreach (var Bx in solid[j])
                        for (var ax = 0; ax < 3; ax++)
                        {
                            bool iPlus = Math.Abs(A.Mx[ax] - Bx.Mn[ax]) < Touch, iMinus = Math.Abs(A.Mn[ax] - Bx.Mx[ax]) < Touch;
                            if (!iPlus && !iMinus)
                                continue;
                            var at = new double[3];
                            var area = 1.0;
                            var ok = true;
                            for (var a = 0; a < 3 && ok; a++)
                            {
                                if (a == ax)
                                {
                                    at[a] = iPlus ? A.Mx[a] : A.Mn[a];
                                    continue;
                                }
                                double lo = Math.Max(A.Mn[a], Bx.Mn[a]), hi = Math.Min(A.Mx[a], Bx.Mx[a]);
                                if (hi - lo < 0.03)
                                    ok = false;
                                at[a] = Math.Round((lo + hi) / 2 + H + (a == 2 ? ZShift : 0), 2) - H - (a == 2 ? ZShift : 0); // (whole centimetres in ship metres)
                                area *= hi - lo;
                            }
                            if (ok && area > best.Area)
                                best = (area, at, ax, iPlus);
                        }
                if (best.Area <= 0)
                    continue;
                var axis = "xyz"[best.Axis];
                All[i].Sock($"j{count[i]++}", best.At, (best.IPlus ? "+" : "-") + axis);
                All[j].Sock($"j{count[j]++}", best.At, (best.IPlus ? "-" : "+") + axis);
            }
    }

    private static bool Meet(Part a, Part b)
    {
        foreach (var s in a.Sockets)
            foreach (var t in b.Sockets)
            {
                var (pa, pb) = ((List<object?>)s["at"]!, (List<object?>)t["at"]!);
                if (Enumerable.Range(0, 3).All(i => Math.Abs(Convert.ToDouble(pa[i]) - Convert.ToDouble(pb[i])) < Touch * 4))
                {
                    var (da, db) = ((string)s["dir"]!, (string)t["dir"]!);
                    if (da[1] == db[1] && da[0] != db[0])
                        return true;
                }
            }
        return false;
    }

    /// <summary>The order to place the pieces in: out from the first over the socket pairs they meet at. Throws naming any piece joined to nothing.</summary>
    public List<string> PlaceOrder(string firstWhat)
    {
        var first = $"{Prefix} {firstWhat}";
        var names = All.Select(q => (string)q.D["name"]!).ToList();
        var seen = new HashSet<int> { names.IndexOf(first) };
        var order = new List<string> { first };
        var queue = new Queue<int>(seen);
        while (queue.Count > 0)
        {
            var i = queue.Dequeue();
            for (var j = 0; j < All.Count; j++)
                if (!seen.Contains(j) && Meet(All[i], All[j]))
                {
                    seen.Add(j);
                    order.Add(names[j]);
                    queue.Enqueue(j);
                }
        }
        if (order.Count != All.Count)
            throw new InvalidOperationException($"ShipGen {Prefix}: pieces joined to nothing: " + string.Join(", ", names.Where((n, i) => !seen.Contains(i))));
        return order;
    }
}
