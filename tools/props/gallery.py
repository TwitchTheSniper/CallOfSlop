#!/usr/bin/env python3
"""Regenerates the Dev pack's prop gallery maps from the Props/ folders.

    python3 -I tools/props/gallery.py            # rewrite the generated galleries in Maps/Dev
    python3 -I tools/props/gallery.py --check    # exit 1 and say which files differ (what the "Props" self-test does)
    python3 -I tools/props/gallery.py --list     # which gallery shows which categories

Every global prop must appear on a Dev map so it can be checked by eye ("Props" self-test). The galleries below are
generated, so a new prop only needs its file in Props/<Category>/ and a run of this tool: it lands on the gallery that
owns its category (or on Prop Gallery More when no gallery claims it and no hand-made Dev map places it by name).
Hand-made Dev maps (Prop Gallery, Prop Yard, Volatile Props, Farm and Rail Props, Gravity Props, the Buildings* maps...)
are never touched.

Layout: one pad per prop (a 5 cm slab the size of its footprint plus a margin), packed left to right into rows of a
fixed width, a new row for each category, aisles between the rows, spawns at both ends of every aisle and
AutoWaypoints last. Categories come in the order the manifest gives them and props in name order within a category,
so adding a prop shifts only the pads after it in its own category's rows; the output is deterministic (no clock, no
randomness, no file-system order).

The game's "Props" self-test compares the committed files to this tool's output byte for byte, so run it after adding,
renaming or resizing a prop, and commit the maps it rewrites. The map fingerprints pinned in
Source/App/SelfTestPackAssets.cs then change too (re-pin them from the self-test's failure message).
"""
from __future__ import annotations

import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PROPS = os.path.join(ROOT, "Props")
DEV = os.path.join(ROOT, "Maps", "Dev")
FLAGS_FOLDER = "Flags"  # Props/Flags holds flag designs, not props

# ---- The manifest -------------------------------------------------------------------------------------------------
# file, map name, order, description, categories (prop "category": the top-level folder unless the file says otherwise),
# row width in metres. "animated" takes every prop with an "anim" part whatever its category (the "Animated props"
# self-test wants them all on this map, so an animated Retail prop is on both galleries); "rest" takes whatever no
# gallery or hand-made Dev map shows. A category gallery shows its whole category, each prop once.
GALLERIES = [
    dict(file="PropGallery2.json", name="Prop Gallery 2", order=952, width=104,
         description="Every outdoor prop (vehicles, rooftop kit, utility, signage, urban furniture) on its own pad, in rows by category.",
         categories=["Vehicles", "Rooftop", "Utility", "Signage", "Urban"]),
    dict(file="PropGallery3.json", name="Prop Gallery 3", order=952, width=78,
         description="Every indoor and garden prop (household, office, kitchen, garden, misc) on its own pad, in rows by category.",
         categories=["Household", "Office", "Kitchen", "Garden", "Misc"]),
    dict(file="AnimatedProps.json", name="Animated Props", order=955, width=80,
         description="Every animated prop (fans, flags, lights, machines...) on its own pad, in rows by category.",
         categories=["animated"]),
    dict(file="MilitaryProps.json", name="Military Props", order=954, width=76,
         description="Every military prop (fortifications, guns, ammo, tanks, planes, trucks) on its own pad, in rows by category.",
         categories=["Military", "Military Vehicles"]),
    dict(file="PropGalleryRetail.json", name="Prop Gallery Retail", order=961, width=88,
         description="Every retail prop (shop fittings, food court, arcade) on its own pad, in rows.",
         categories=["Retail"]),
    dict(file="SpaceProps.json", name="Space Props", order=971, width=90,
         description="Every Space pack prop (stations, yards, lunar surface, salvage) on its own pad, in rows.",
         categories=["Space"]),
    dict(file="PropGalleryMore.json", name="Prop Gallery More", order=953, width=80,
         description="Every prop no other Dev map shows, on its own pad, in rows by category. Generated by tools/props/gallery.py.",
         categories=["rest"]),
]
GENERATED_FILES = [g["file"] for g in GALLERIES]

MARGIN = 0.6     # pad beyond the footprint on each side
GAP = 0.8        # between pads in a row
AISLE = 4.5      # between rows (a 4 m waypoint grid always lands in it)
SIDE = 5.0       # open ground between the rows and the perimeter wall
WAYPOINTS = 4
MAX_SPAWNS = 18
MIN_SPAWNS = 12
SKY = [0.56, 0.62, 0.7]
PAD_COLOR = [0.48, 0.48, 0.5]
GROUND_COLOR = [0.34, 0.36, 0.36]
WALL_COLOR = [0.5, 0.52, 0.55]


# ---- Props --------------------------------------------------------------------------------------------------------

def rotation_matrix(deg):
    """Row-major 3x3 for System.Numerics' CreateFromYawPitchRoll(yaw, pitch, roll): yaw about Y, then pitch about X, then roll about Z."""
    pitch, yaw, roll = (math.radians(v) for v in deg)
    cy, sy = math.cos(yaw), math.sin(yaw)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cr, sr = math.cos(roll), math.sin(roll)
    ry = [[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]
    rx = [[1, 0, 0], [0, cp, -sp], [0, sp, cp]]
    rz = [[cr, -sr, 0], [sr, cr, 0], [0, 0, 1]]

    def mul(a, b):
        return [[math.fsum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]

    return mul(mul(ry, rx), rz)


def part_bounds(part):
    size = part.get("size", [1, 1, 1])
    off = part.get("offset", [0, 0, 0])
    half = [s / 2 for s in size]
    rot = part.get("rotation")
    if rot and any(abs(v) > 1e-9 for v in rot):
        m = rotation_matrix(rot)
        ext = [math.fsum(abs(m[i][j]) * half[j] for j in range(3)) for i in range(3)]
    else:
        ext = half
    # Quantised to 0.1 mm: libm's sin/cos differ in their last bit between platforms, and a layout that is a sum of
    # hundreds of footprints must round the same way everywhere (the self-test compares the files byte for byte).
    return [round(off[i] - ext[i], 4) for i in range(3)], [round(off[i] + ext[i], 4) for i in range(3)]


def flat_parts(raw, name, visiting=()):
    """A prop's parts with every "use" part (a prefab piece, Props/README.md "Prefabs") replaced by the used prop's parts
    moved, turned (yaw) and scaled the way the game's loader does it."""
    d = raw[name]
    out = []
    for p in d["parts"]:
        if "use" not in p:
            out.append(p)
            continue
        used = p["use"].strip()
        if used.lower() in {v.lower() for v in visiting} or used.lower() == name.lower():
            sys.exit(f"gallery.py: prop '{name}' uses itself through {' -> '.join(visiting + (name, used))}")
        key = next((k for k in raw if k.lower() == used.lower()), None)
        if key is None:
            sys.exit(f"gallery.py: prop '{name}' uses unknown prop '{used}'")
        pos = p.get("pos", p.get("offset", [0, 0, 0]))
        rot = list(p.get("rotation", [0, 0, 0]))
        if "yaw" in p:
            rot[1] = p["yaw"]
        scale = p.get("scale", 1)
        m = rotation_matrix(rot)
        for q in flat_parts(raw, key, visiting + (name,)):
            off = q.get("offset", [0, q.get("size", [1, 1, 1])[1] / 2, 0])
            off = [v * scale for v in off]
            turned = [math.fsum(m[i][j] * off[j] for j in range(3)) for i in range(3)]
            qrot = list(q.get("rotation", [0, 0, 0]))
            if "yaw" in q:
                qrot[1] = q["yaw"]
            if "pitch" in q:
                qrot[0] = q["pitch"]
            if "roll" in q:
                qrot[2] = q["roll"]
            r = dict(q)
            r.pop("yaw", None)
            r.pop("pitch", None)
            r.pop("roll", None)
            r["size"] = [v * scale for v in q.get("size", [1, 1, 1])]
            r["offset"] = [pos[i] + turned[i] for i in range(3)]
            r["rotation"] = rot if any(abs(v) > 1e-9 for v in (rot[0], rot[2])) else [qrot[0], qrot[1] + rot[1], qrot[2]]
            out.append(r)
    return out


def load_props():
    """Every global prop: name -> dict(category, min, max, animated, file). Prefabs are flattened like the game does."""
    raw = {}
    files = {}
    folders = {}
    for dirpath, dirnames, fnames in os.walk(PROPS):
        dirnames.sort()
        for fn in sorted(fnames):
            if not fn.endswith(".json"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, fn), PROPS).replace("\\", "/")
            folder = rel.split("/")[0] if "/" in rel else "Misc"
            if folder.lower() == FLAGS_FOLDER.lower():
                continue
            with open(os.path.join(dirpath, fn), encoding="utf-8") as f:
                d = json.load(f)
            if "parts" not in d or "name" not in d:
                continue
            name = d["name"].strip()
            if name.lower() in {k.lower() for k in raw}:
                sys.exit(f"gallery.py: two props are called '{name}' ({rel} and {files[name]})")
            raw[name] = d
            files[name] = rel
            folders[name] = folder
    props = {}
    for name, d in raw.items():
        parts = flat_parts(raw, name)
        lo = [1e9] * 3
        hi = [-1e9] * 3
        for p in parts:
            a, b = part_bounds(p)
            lo = [min(lo[i], a[i]) for i in range(3)]
            hi = [max(hi[i], b[i]) for i in range(3)]
        cat = (d.get("category") or "").strip() or folders[name]
        props[name] = dict(category=cat, min=lo, max=hi, file=files[name], animated=any("anim" in p for p in parts))
    return props


def shadowed_by_dev_pack():
    """Names of the Dev pack's own props (Maps/Dev/Props): a gallery names the global one with the "global:" prefix."""
    names = set()
    folder = os.path.join(DEV, "Props")
    if os.path.isdir(folder):
        for fn in sorted(os.listdir(folder)):
            if fn.endswith(".json"):
                with open(os.path.join(folder, fn), encoding="utf-8") as f:
                    d = json.load(f)
                if "name" in d:
                    names.add(d["name"].strip().lower())
    return names


def shown_on_hand_made_maps():
    """Prop names placed by a Prop op on a Dev map this tool doesn't generate (Clutter is random, so it doesn't count)."""
    shown = set()
    for fn in sorted(os.listdir(DEV)):
        if not fn.endswith(".json") or fn == "pack.json" or fn in GENERATED_FILES:
            continue
        with open(os.path.join(DEV, fn), encoding="utf-8") as f:
            d = json.load(f)
        for op in d.get("ops", []):
            if op.get("op") == "Prop" and isinstance(op.get("name"), str):
                shown.add(op["name"].replace("global:", "").strip().lower())
    return shown


# ---- Layout -------------------------------------------------------------------------------------------------------

def r2(v):
    v = round(v + 0.0, 2)
    return 0.0 if v == 0 else v


def num(v):
    """A number as the maps write them: integers bare, otherwise two decimals at most."""
    v = r2(v)
    return str(int(v)) if float(v).is_integer() else repr(v)


def assign(props, hand_made):
    """Which gallery shows which props: name -> list of (category, [names])."""
    claimed = set()
    result = {}
    for g in GALLERIES:
        groups = []
        for cat in g["categories"]:
            if cat == "animated":
                names = [n for n, p in props.items() if p["animated"]]
                by_cat = {}
                for n in names:
                    by_cat.setdefault(props[n]["category"], []).append(n)
                for c in sorted(by_cat, key=str.lower):
                    groups.append((c, sorted(by_cat[c], key=str.lower)))
            elif cat == "rest":
                names = [n for n, p in props.items() if n not in claimed and not p["animated"] and n.lower() not in hand_made]
                by_cat = {}
                for n in names:
                    by_cat.setdefault(props[n]["category"], []).append(n)
                for c in sorted(by_cat, key=str.lower):
                    groups.append((c, sorted(by_cat[c], key=str.lower)))
            else:
                names = sorted((n for n, p in props.items() if p["category"].lower() == cat.lower() and n not in claimed), key=str.lower)
                groups.append((cat, names))
                claimed.update(names)
        result[g["file"]] = groups
    return result


def layout(gallery, groups, props, shadowed):
    width = gallery["width"]
    rows = []  # each: list of (name, pad_w, pad_d)
    for _cat, names in groups:
        if not names:
            continue
        row = []
        x = 0.0
        for n in names:
            lo, hi = props[n]["min"], props[n]["max"]
            pw = (hi[0] - lo[0]) + 2 * MARGIN
            pd = (hi[2] - lo[2]) + 2 * MARGIN
            if row and x + pw > width:
                rows.append(row)
                row = []
                x = 0.0
            row.append((n, pw, pd))
            x += pw + GAP
        if row:
            rows.append(row)
    if not rows:
        return None
    # math.fsum, not sum(): Python 3.12 made sum() of floats compensated, so the two round differently on long rows.
    depth = math.fsum(max(p[2] for p in row) for row in rows) + AISLE * (len(rows) - 1)
    half_x = math.ceil(width / 2 + SIDE)
    half_z = math.ceil(depth / 2 + SIDE)
    ops = [
        {"op": "Ground", "color": GROUND_COLOR},
        {"op": "Perimeter", "height": 4, "color": WALL_COLOR},
    ]
    z = -depth / 2
    aisles = []
    for i, row in enumerate(rows):
        row_d = max(p[2] for p in row)
        row_w = math.fsum(p[1] for p in row) + GAP * (len(row) - 1)
        x = -row_w / 2
        for n, pw, pd in row:
            lo, hi = props[n]["min"], props[n]["max"]
            x0, x1 = x, x + pw
            z0, z1 = z, z + pd
            cx, cz = (x0 + x1) / 2, (z0 + z1) / 2
            px = cx - (lo[0] + hi[0]) / 2  # the prop's origin so its footprint is centred on the pad
            pz = cz - (lo[2] + hi[2]) / 2
            ops.append({"op": "Block", "x0": r2(x0), "y0": 0, "z0": r2(z0), "x1": r2(x1), "y1": 0.05, "z1": r2(z1), "color": PAD_COLOR})
            label = ("global:" + n) if n.lower() in shadowed else n
            ops.append({"op": "Prop", "name": label, "x": r2(px), "z": r2(pz), "yaw": 0})
            x += pw + GAP
        if i + 1 < len(rows):
            aisles.append(z + row_d + AISLE / 2)
        z += row_d + AISLE
    # Spawns: the two ends of every aisle, plus the open ground before the first row and after the last.
    spots = [-depth / 2 - SIDE / 2] + aisles + [depth / 2 + SIDE / 2]
    sx = width / 2 + SIDE / 2
    spawns = []
    for sz in spots:
        spawns.append((-sx, sz))
        spawns.append((sx, sz))
    if len(spawns) < MIN_SPAWNS:  # a short gallery: more along the open strips before the first row and after the last
        for x in (-width / 4, 0.0, width / 4):
            spawns.append((x, spots[0]))
            spawns.append((x, spots[-1]))
    if len(spawns) > MAX_SPAWNS:
        step = len(spawns) / MAX_SPAWNS
        spawns = [spawns[int(i * step)] for i in range(MAX_SPAWNS)]
    for x, sz in spawns:
        ops.append({"op": "Spawn", "x": r2(x), "z": r2(sz)})
    ops.append({"op": "AutoWaypoints", "spacing": WAYPOINTS})
    return dict(halfX=half_x, halfZ=half_z, ops=ops)


def fmt_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return num(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(fmt_value(x) for x in v) + "]"
    raise TypeError(type(v))


def render(gallery, built, shown_count):
    lines = [
        "{",
        '  "format": "call-of-slop-map/1",',
        f'  "name": {json.dumps(gallery["name"])},',
        f'  "description": {json.dumps(gallery["description"] + f" {shown_count} props. Generated by tools/props/gallery.py: do not edit by hand.")},',
        '  "author": "Call of Slop",',
        f'  "order": {gallery["order"]},',
        f'  "halfX": {built["halfX"]},',
        f'  "halfZ": {built["halfZ"]},',
        '  "sky": [',
    ]
    for i, c in enumerate(SKY):
        lines.append(f"    {c}{',' if i < len(SKY) - 1 else ''}")
    lines.append("  ],")
    lines.append('  "ops": [')
    ops = built["ops"]
    for i, op in enumerate(ops):
        body = ", ".join(f"{json.dumps(k)}: {fmt_value(v)}" for k, v in op.items())
        lines.append("    {" + body + "}" + ("," if i < len(ops) - 1 else ""))
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate():
    props = load_props()
    shadowed = shadowed_by_dev_pack()
    hand_made = shown_on_hand_made_maps()
    groups = assign(props, hand_made)
    out = {}
    for g in GALLERIES:
        built = layout(g, groups[g["file"]], props, shadowed)
        if built is None:
            out[g["file"]] = None  # nothing to show: the file must not exist
            continue
        count = sum(len(n) for _, n in groups[g["file"]])
        out[g["file"]] = render(g, built, count)
    return out, groups


def main(argv):
    out, groups = generate()
    if "--list" in argv:
        for g in GALLERIES:
            cats = ", ".join(f"{c} ({len(n)})" for c, n in groups[g["file"]] if n)
            print(f"{g['file']}: {g['name']}: {cats or '(nothing: no file)'}")
        return 0
    differ = []
    for fn, text in out.items():
        path = os.path.join(DEV, fn)
        if text is None:
            if os.path.exists(path):
                differ.append(fn)
                if "--check" not in argv:
                    os.remove(path)
                    print(f"removed {fn} (nothing left to show)")
            continue
        try:
            with open(path, encoding="utf-8", newline="") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != text:
            differ.append(fn)
            if "--check" not in argv:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
                print(f"wrote {fn} ({sum(len(n) for _, n in groups[fn])} props)")
    if "--check" in argv:
        if differ:
            print("gallery maps out of date: " + ", ".join(differ) + ". Run: python3 -I tools/props/gallery.py")
            return 1
        print("gallery maps up to date")
        return 0
    if not differ:
        print("gallery maps already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
